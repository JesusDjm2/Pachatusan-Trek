    <h2 class="section-title text-uppercase h3">PORTERS &mdash; INCA TRAIL</h2>
    <h3 class="kicker text-uppercase">BACKGROUND</h3>
    <p>The Peruvian government protects the Historical Sanctuary of Machu Picchu in different ways: from a
        cultural perspective through the Ministry of Culture; environmentally through the Ministry of
        Environment; and socially through the Ministry of Labour. These state institutions regulate
        tourism within the Historical Sanctuary of Machu Picchu (SHMP).</p>
    <h3 class="kicker text-uppercase">OUR ACTIVITIES INSIDE THE HISTORICAL SANCTUARY OF MACHU PICCHU</h3>
    <p>For Pachatusantrek S.A.C., being respectful towards our staff, the laws in our country and the quality
        of the service that we provide are of supreme importance. For these reasons our camping equipment has
        been carefully chosen to fulfill these three basic requirements.</p>
    <p>It is also important to know that the rules of the Historical Sanctuary of Machu Picchu <strong>prohibit
            the use of horses or mules</strong> to carry equipment along the Inca Trail&mdash;the hooves
        damage the stone path. <strong>Only porters are allowed</strong>.</p>
    <p><strong>The Porters Law</strong>, created to protect workers on the network of Inca Trails, sets the
        weight limits that each porter is allowed to carry&mdash;we are therefore forced to minimize the
        load carried on behalf of the porters. <strong>Maximum 20kg / 44lb per porter</strong>, as stated by
        the law. The weight permitted for each trekker (including sleeping bag) is
        <strong>5kg / 11lb</strong>; we ask for your understanding and cooperation, as trekkers can carry
        any excess in their day packs.</p>
    <p>Following the Porters Law, Pachatusantrek provides porters with the <strong>equipment required to do
            their work in the best way</strong>.</p>
    <h3 class="kicker text-uppercase" id="porters-gear">CAMPING EQUIPMENT FOR OUTDOOR STAFF</h3>
    <p>As required, Pachatusantrek provides: tents, trekking shoes, backpacks with waist straps and back
        support, fleece jacket, lumbar support for lifting, foam mattress, sleeping bag, tent, torch, water
        bottle, work uniform (long- and short-sleeved shirts, fleece jacket, raincoat, pants), and rain
        poncho.</p>
